// Roadmap-6 A8: everything the model is told on a first turn, as one reviewable file. A prompt change must update
// the snapshot (UPDATE_SNAPSHOT=1 npm test), so the review sees exactly what the model will read.
import { BACKGROUND_CONTEXT as ctx } from '@earendil-works/chord/context'
import { openNodeSqliteDatabase } from '@earendil-works/chord/sqlite/node'
import { fauxAssistantMessage, fauxProvider, fauxText } from '@earendil-works/pi-ai/providers/faux'
import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'
import { test } from 'node:test'
import { pluginDefaultsFromEnv, UserSpace } from '../src/index.ts'
import { diskEnv } from './fixtures.ts'
import { COMPACTION_INSTRUCTIONS } from '../src/agent/compaction.ts'
import { projectDir } from '@gense/protocol'
