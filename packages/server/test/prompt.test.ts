// Roadmap-6 A8: everything the model is told on a first turn, as one reviewable file. A prompt change must update
// the snapshot (UPDATE_SNAPSHOT=1 npm test), so the review sees exactly what the model will read.
import { BACKGROUND_CONTEXT as ctx } from '@earendil-works/chord/context'
import { openNodeSqliteDatabase } from '@earendil-works/chord/sqlite/node'
import { fauxAssistantMessage, fauxProvider, fauxText } from '@earendil-works/pi-ai/providers/faux'
import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'
import { test } from 'node:test'
import { pluginDefaultsFromEnv, UserSpace } from '../src/index.ts'
import { diskEnv } from './fixtures.ts'
import { COMPACTION_INSTRUCTIONS } from '../src/agent/compaction.ts'
import { projectDir } from '@gense/protocol'

const SNAPSHOT = new URL('./prompt.snapshot.md', import.meta.url)

interface SystemMessage {
  sections: Record<string, string>
  toolsAdded?: { name: string; description?: string; parameters?: unknown }[]
}

/** The first request's system message, with every built-in plugin on, a sandbox and a fixed clock. */
async function firstSystemMessage(inProject = false): Promise<SystemMessage> {
  const faux = fauxProvider({ models: [{ id: 'faux-1', name: 'Faux' }] })
  faux.setResponses([() => fauxAssistantMessage([fauxText('ok')])])
  let system: SystemMessage | undefined
  const provider = faux.provider as unknown as Record<'stream' | 'streamSimple', (m: unknown, c: { messages: unknown[] }, o: unknown) => unknown>
  for (const k of ['stream', 'streamSimple'] as const) {
    const original = provider[k].bind(provider)
    provider[k] = (model, context, options) => {
      system ??= context.messages[0] as SystemMessage
      return original(model, context, options)
    }
  }
  const m = faux.getModel()
  const option = { provider: m.provider, id: m.id, name: m.name }
  const space = await UserSpace.open(await openNodeSqliteDatabase(':memory:'), {
    models: { providers: [faux.provider], options: [option], defaultModel: option },
    env: await diskEnv(),
    sandbox: true,
    secretKey: 'k',
    plugins: { defaults: pluginDefaultsFromEnv({ DEEPSEEK_API_KEY: 'k', PROVIDER_BASE_URL: 'http://image.invalid', PROVIDER_AUTH_TOKEN: 'k' }) },
    now: () => Date.UTC(2026, 10, 11, 20),
  })
  try {
    await space.preferences.set({ name: 'Ada', instructions: 'Keep answers short.', timeZone: 'Asia/Shanghai' })
    // Stable ids in real SQLite keep this scene reviewable without replacing parts of the captured prompt.
    const projectId = 'project-research', now = Date.UTC(2026, 10, 11, 20)
    if (inProject) {
      await space.db.run('INSERT INTO projects (id, name, color, instructions, createdAt, updatedAt) VALUES (?, ?, ?, ?, ?, ?)', projectId, 'Research', 2, 'Use SI units and cite primary sources.', now, now)
      const env = await space.workspace.env('/data')
      const made = await env.createDir(projectDir(projectId), { recursive: true }, ctx)
      assert.ok(made.ok)
      const upload = await space.workspace.upload('reference.md', new TextEncoder().encode('Reference material.'))
      await space.projects.addFiles(projectId, [upload.id])
    }
    const tree = await space.createTree(inProject ? projectId : undefined)
    if (inProject) {
      await space.db.run('INSERT INTO memories (id, text, source, treeId, projectId, enabled, createdAt, updatedAt) VALUES (?, ?, ?, ?, ?, ?, ?, ?)', 'memory-global', 'Prefers metric units.', 'manual', null, null, 1, now, now)
      await space.db.run('INSERT INTO memories (id, text, source, treeId, projectId, enabled, createdAt, updatedAt) VALUES (?, ?, ?, ?, ?, ?, ?, ?)', 'memory-project', 'Researches climate models.', 'model', tree.id, projectId, 1, now, now + 1)
    }
    await space.send(tree.id, { text: 'hi', requestId: 'r' })
    await space.harness.waitForIdle(ctx)
  } finally {
    await space.close()
  }
  assert.ok(system, 'the model was called')
  return system
}

function render(system: SystemMessage) {
  const out = ['# First-turn prompt', '', 'Generated by test/prompt.test.ts; do not edit. Regenerate with `UPDATE_SNAPSHOT=1 npm test`.', '']
  for (const [name, text] of Object.entries(system.sections)) out.push(`## Section: ${name}`, '', '````text', text, '````', '')
  for (const t of system.toolsAdded ?? [])
    out.push(`## Tool: ${t.name}`, '', '````text', t.description ?? '', '````', '', '````json', JSON.stringify(t.parameters ?? {}, null, 2), '````', '')
  out.push('## Context compaction instructions', '', '````text', COMPACTION_INSTRUCTIONS, '````', '')
  return out.join('\n')
}

test('A8 (roadmap-6), A2/A8/A9/A10 (roadmap-7): first-turn and project prompts match the snapshot', async () => {
  const system = await firstSystemMessage()
  const project = await firstSystemMessage(true)
  const { memory: baseMemory, ...baseSections } = system.sections
  const { memory, project: projectText, ...projectSections } = project.sections
  assert.ok(baseMemory && memory && projectText)
  assert.deepEqual(projectSections, baseSections, 'the stable sections are identical in both conversations')
  assert.deepEqual(project.toolsAdded, system.toolsAdded, 'the tools are identical in both conversations')
  assert.equal(memory.split('\n').filter(line => line.startsWith('- [')).length, 2)
  assert.match(projectText, /reference\.md \(19 B\)/)
  const difference = ['# Project conversation prompt', '', 'A conversation in Research, with two memories and one project file. All other sections and tools are identical to the first-turn baseline above (checked by the test).', '']
  for (const [name, section] of [['memory', memory], ['project', projectText]]) difference.push(`## Section: ${name}`, '', '````text', section!, '````', '')
  const text = render(system) + '\n' + difference.join('\n')
  if (process.env.UPDATE_SNAPSHOT) writeFileSync(SNAPSHOT, text)
  assert.equal(text, readFileSync(SNAPSHOT, 'utf8'), 'the prompt changed: review the diff and rerun with UPDATE_SNAPSHOT=1')
  // A10: the date is the user's, not the server's: 20:00 UTC on 11 Nov is already 12 Nov in Shanghai.
  assert.match(system.sections.assistant!, /Today is Thursday, 2026-11-12 \(the user's time zone, Asia\/Shanghai\)/)
  // A9: the bash description agrees with the timeout it applies.
  assert.match(system.toolsAdded!.find((t) => t.name === 'bash')!.description!, /after 120 seconds/)
  // A11: no Skill description in the list runs past the limit.
  for (const line of system.sections.skills!.split('\n').filter((l) => l.startsWith('- '))) assert.ok(line.replace(/ \([^)]*\)$/, '').length < 320, line)
})
