// Writes the generative UI's system prompt and parser schema into core (docs/plans/openui.md), from the component
// library the browser renders with, so the server checks programs against the same components. Bundled by
// `vite build --ssr` first (the library imports CSS and TSX); `--check` fails when the committed file is stale.
import { generateSystemPrompt } from '@openuidev/react-lang'
import { readFileSync, writeFileSync } from 'node:fs'
import { library, promptOptions } from '../src/plugins/ui/genui/library.ts'

const out = process.argv[2]!
// The prompt is built from the library's spec (signatures and descriptions), not from the library object itself.
const spec = library.toSpec()
const prompt = generateSystemPrompt({ library: spec, promptOptions })
if (prompt.includes('undefined —')) throw new Error(`prompt has an undefined signature: ${prompt.slice(prompt.indexOf('undefined —') - 80, prompt.indexOf('undefined —') + 80)}`)
const source = `// Generated by \`npm run genui -w @gense/web\` from packages/web/src/plugins/ui/genui; do not edit.
export const UI_PROMPT = ${JSON.stringify(prompt)}
export const UI_ROOT = ${JSON.stringify(library.root)}
export const UI_SIGNATURES: Record<string, string> = ${JSON.stringify(Object.fromEntries(Object.entries(spec.components).map(([name, c]) => [name, c.signature])))}
export const UI_SCHEMA = ${JSON.stringify(library.toJSONSchema())} as const
`
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== source) {
    console.error(`${out} is stale: run npm run genui -w @gense/web`)
    process.exit(1)
  }
} else writeFileSync(out, source)
