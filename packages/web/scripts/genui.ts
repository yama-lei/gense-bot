// Writes what the server needs to know about the generative UI (docs/plans/openui.md, roadmap-6 A4), from the component
// library the browser renders with, so the server checks programs against the same components:
// - packages/server/src/plugins/genui/generated.ts: the parser schema and signatures, for checking `ui_render`;
// - packages/server/skills/generative-ui/references/: the language reference and the good practices the model reads
//   from the `generative-ui` Skill before its first page, instead of carrying them in every system prompt.
// Bundled by `vite build --ssr` first (the library imports CSS and TSX); `--check` fails when a committed file is stale.
import { generateSystemPrompt } from '@openuidev/react-lang'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { library, promptOptions } from '../src/plugins/ui/genui/library.ts'
import { exampleShoppingList, exampleSteps, exampleTrip, rules } from '../src/plugins/ui/genui/prompt-options.ts'

const server = resolve(process.argv[2]!)
const header = '<!-- Generated by `npm run genui -w @gense/web` from packages/web/src/plugins/ui/genui; do not edit. -->\n\n'

// The prompt is built from the library's spec (signatures and descriptions), not from the library object itself.
const spec = library.toSpec()
const full = generateSystemPrompt({ library: spec, promptOptions: { ...promptOptions, examples: [], additionalRules: [] } })
if (full.includes('undefined —')) throw new Error(`prompt has an undefined signature: ${full.slice(full.indexOf('undefined —') - 80, full.indexOf('undefined —') + 80)}`)
// Everything from the syntax rules on; the preamble is the server's own (plugins/display.ts).
const start = full.indexOf('## Syntax Rules')
if (start < 0) throw new Error('prompt has no "## Syntax Rules" section')
const language = `${header}# openui-lang reference\n\n${full.slice(start).trim()}\n`

const practices = `${header}# Good practices

${rules.map((r) => `- ${r}`).join('\n')}

## Examples

### A guest stepper that rescales a shopping list, with a checklist and a copy button

\`\`\`openui-lang
${exampleShoppingList}
\`\`\`

### A composed trip answer: photos, facts, day rows and a short form

\`\`\`openui-lang
${exampleTrip}
\`\`\`

### Step-by-step instructions with a drawing for each step, driven by $step

\`\`\`openui-lang
${exampleSteps}
\`\`\`
`

const generated = `// Generated by \`npm run genui -w @gense/web\` from packages/web/src/plugins/ui/genui; do not edit.
export const UI_ROOT = ${JSON.stringify(library.root)}
export const UI_SIGNATURES: Record<string, string> = ${JSON.stringify(Object.fromEntries(Object.entries(spec.components).map(([name, c]) => [name, c.signature])))}
export const UI_SCHEMA = ${JSON.stringify(library.toJSONSchema())} as const
`

const outputs: [string, string][] = [
  [resolve(server, 'src/plugins/genui/generated.ts'), generated],
  [resolve(server, 'skills/generative-ui/references/language.md'), language],
  [resolve(server, 'skills/generative-ui/references/practices.md'), practices],
]
if (process.argv.includes('--check')) {
  const stale = outputs.filter(([path, text]) => { try { return readFileSync(path, 'utf8') !== text } catch { return true } })
  if (stale.length) {
    console.error(`${stale.map(([p]) => p).join(', ')} stale: run npm run genui -w @gense/web`)
    process.exit(1)
  }
} else for (const [path, text] of outputs) writeFileSync(path, text)
